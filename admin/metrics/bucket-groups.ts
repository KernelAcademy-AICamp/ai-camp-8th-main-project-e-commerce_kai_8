// 추천 유형(source_bucket)을 계열로 묶는 기준. **여기 한 곳에서만 정한다.**
//
// 여러 지표가 같은 기준을 써야 한다. 카드마다 따로 적으면 한쪽만 고쳤을 때
// 표들이 서로 다른 분류로 계산돼 숫자가 어긋난다.

/**
 * 계열을 내는 SQL 조각. `c_events`의 `source_bucket`이 보이는 자리에 넣는다.
 * 테이블 별칭을 붙이지 않았으므로 **source_bucket이 하나만 보이는 범위**에서 쓴다.
 *
 * 분류 근거는 피드를 만드는 SQL(`backend/supabase/migrations/20260816120000_c_mix_page.sql`)이
 * 각 유형을 **어떻게 고르는가**이다.
 *
 * | 유형 | 고르는 방법 | 계열 |
 * | --- | --- | --- |
 * | `longterm` | 장기 취향 벡터와 가까운 순 | 익숙함 |
 * | `session` | 이번 세션 취향 벡터와 가까운 순 | 익숙함 |
 * | `similar` | "이 스타일로 계속 탐색"의 유사 상품 | 익숙함 |
 * | `partial` | 성별·가격대만 맞추고 **이미지는 무작위** | 부분 일치 |
 * | `opposite` | 그래픽 유무를 **뒤집어** 고름 | 새로움 |
 * | `diversity` | 순수 무작위 | 새로움 |
 *
 * **`partial`은 일부러 어느 쪽에도 넣지 않았다.** 성별·가격대는 맞으니 완전한 낯섦이
 * 아니고, 이미지 유사도를 전혀 쓰지 않으니 익숙함도 아니다. 지금 어느 쪽에 붙여도
 * 근거가 없어서, 숫자를 본 뒤에 정하기로 했다 (2026-08-21 제품 책임자 결정).
 * 합칠 때 고칠 곳은 이 표 한 줄이다.
 *
 * `기타` = source_bucket이 비어 있는 노출. 검색 결과 화면처럼 추천 믹스를 거치지
 * 않은 경로다. 숨기지 않고 남겨 둔다 — 합계가 맞는지 볼 수 있어야 한다.
 */
export const BUCKET_GROUP_SQL = `
    case source_bucket
      when 'longterm'  then '익숙함'
      when 'session'   then '익숙함'
      when 'similar'   then '익숙함'
      when 'partial'   then '부분 일치'
      when 'opposite'  then '새로움'
      when 'diversity' then '새로움'
      else '기타'
    end`;

/**
 * 유효 세션의 최소 노출 수.
 *
 * 열자마자 닫은 세션이 지표에 섞이면 "검색 안 함"·"아무것도 안 누름"이 부풀려진다.
 * 10개는 2열 masonry에서 한 화면을 조금 넘기는 양이다 — **훑기 시작은 했다**고
 * 볼 수 있는 최소선.
 *
 * ponytail: 10은 눈대중 값이다. 유효 세션이 거의 안 남으면 낮추고, 짧은 세션이
 * 여전히 섞여 보이면 올린다. PRD가 "유효 탐색"을 여러 번 쓰면서 정의하지 않아
 * 이 값이 사실상 첫 정의가 된다 — 다른 지표를 만들 때도 이 상수를 쓴다.
 */
export const MIN_IMPRESSIONS_SQL = "10";
